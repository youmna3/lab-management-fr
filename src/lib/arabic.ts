// Normalize Arabic governorate & area names so different spellings match
// (strip diacritics/tatweel, unify alef/ya/ta-marbuta, drop spaces and leading "ال").
export function normalizeArabic(s: string | null | undefined): string {
  return (s ?? "")
    .replace(/[ً-ْٰـ]/g, "")
    .replace(/[أإآ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/\s+/g, "")
    .replace(/^ال/, "")
    .trim();
}

export function cleanArabicString(val: unknown): string {
  if (val === null || val === undefined) return "";
  let str = String(val).trim().replace(/\s+/g, " ");
  // Strip diacritics / tashkeel
  str = str.replace(/[ً-ْٰـ]/g, "");
  // Normalize alefs
  str = str.replace(/[أإآ]/g, "ا");
  // Normalize yaa
  str = str.replace(/ى/g, "ي");
  // Normalize teh marbuta
  str = str.replace(/ة/g, "ه");
  return str.trim();
}

