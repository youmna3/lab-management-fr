export function getGovForArea(area: string | null | undefined): string {
  if (!area) return "";
  const str = String(area).trim();
  if (!str) return "";

  // 1. Direct match with cleanArabicString
  const normClean = cleanArabicString(str);
  for (const [a, g] of Object.entries(EGYPT_AREA_TO_GOV)) {
    if (cleanArabicString(a) === normClean) return g;
  }

  // 2. Normalized Arabic match (handles leading "ال", diacritics, alefs, ya, teh marbuta)
  const normArabic = normalizeArabic(str);
  for (const [a, g] of Object.entries(EGYPT_AREA_TO_GOV)) {
    if (normalizeArabic(a) === normArabic) return g;
  }

  // 3. Strip common Egyptian administrative prefixes (مركز, مدينة, قسم, بندر, حي, قرية)
  const stripped = str
    .replace(/^(مركز|مدينة|قسم|بندر|حي|قرية)\s+/i, "")
    .trim();
  if (stripped && stripped !== str) {
    const strippedNorm = normalizeArabic(stripped);
    for (const [a, g] of Object.entries(EGYPT_AREA_TO_GOV)) {
      if (normalizeArabic(a) === strippedNorm) return g;
    }
  }

  // 4. Check if the string contains any known area name (min length 3 to prevent false positives)
  for (const [a, g] of Object.entries(EGYPT_AREA_TO_GOV)) {
    const normA = normalizeArabic(a);
    if (normA.length >= 3 && normArabic.includes(normA)) {
      return g;
    }
  }

  // 5. English / Canonical fallback
  const canonical = normalizeAreaCanonical(str);
  if (canonical && canonical !== str) {
    const canonNorm = normalizeArabic(canonical);
    for (const [a, g] of Object.entries(EGYPT_AREA_TO_GOV)) {
      if (normalizeArabic(a) === canonNorm) return g;
    }
    return canonical;
  }

  return str;
}

